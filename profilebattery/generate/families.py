"""Registry: which family grammar builds a given construct's A cores.

Also the route that lets a *sibling* construct's A cores serve as B prompts. Where two
constructs share a surface token — `for` across For and the four comprehensions, `if`
across If and IfExp, `[` across Subscript and List — an A core of one is by construction
a prompt in which the other's token is present and the other's construct is absent. So
the strongest other-role B subtype costs nothing: it is generated by the A grammar and
verified by the same machinery.
"""

from __future__ import annotations

import numpy as np

from . import builtins_family, comprehensions, compound, expressions, simple
from .bpool import BCore
from .core import Core
from ..inventory.tokens import siblings

MODULES = {"compound": compound, "simple": simple, "expressions": expressions,
           "comprehensions": comprehensions}

FAMILY_OF: dict[str, str] = {}
for _fam, _mod in MODULES.items():
    for _c in _mod.SPECS:
        FAMILY_OF[_c] = _fam

#: cap on |A-B| per family. Tighter where the programme dates the construct itself,
#: so cross-contamination between dated constructs is the dangerous kind.
CAP = {"compound": 0.15, "comprehensions": 0.15, "simple": 0.25, "expressions": 0.25,
       "builtin": 0.25}


#: companions a construct's B set cannot carry for grammatical reasons, so the cap does
#: not apply to them. `break` and `continue` may appear only inside a loop, and a B
#: prompt for `For` may contain no For — so matching A's early-exit bodies would require
#: putting a `while` in every such B prompt, trading a small asymmetry for a larger one.
#: These are declared limitations of the contrast, recorded rather than capped.
STRUCTURAL_EXEMPT: dict[str, tuple[str, ...]] = {
    "For": ("Break", "Continue"), "AsyncFor": ("Break", "Continue"),
    "While": ("Break", "Continue"),
}


def family_of(construct: str) -> str:
    return FAMILY_OF.get(construct, "builtin")


def build_a_cores(construct: str, n: int, rng: np.random.Generator) -> list[Core]:
    fam = family_of(construct)
    if fam == "builtin":
        return builtins_family.build_cores(construct, n, rng)
    return MODULES[fam].build_cores(construct, n, rng)


def sibling_b_cores(construct: str, n: int, rng: np.random.Generator) -> list[BCore]:
    """B cores from the A grammars of constructs sharing this one's token."""
    out: list[BCore] = []
    for sib in siblings(construct):
        if sib not in FAMILY_OF:
            continue
        per = max(1, n // max(1, len(siblings(construct))))
        for core in build_a_cores(sib, per, rng):
            out.append(BCore(core_id=f"{construct}/B:sibling:{sib}/{core.core_id}",
                             construct=construct, subtype=f"other_role:sibling:{sib}",
                             shape_index=0,
                             render=lambda m, c, r, _k=core: _k.render(m, c, r).lines))
    return out
